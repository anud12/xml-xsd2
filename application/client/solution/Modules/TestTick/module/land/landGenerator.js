import { memoize } from "../../util/memoize";
export const landTypeKey = "land";
export const landGenerator = memoize((hostApi) => {
    return hostApi.runtime.entityBlueprint.oneOf(() => [
        {
            textMap: {
                name: hostApi.runtime.stringBlueprint.oneOf(() => [
                    hostApi.runtime.string.of(names[0]),
                    ...names.slice(1).map(hostApi.runtime.string.of),
                ]).generateValue(),
            },
            numberMap: {
                [landTypeKey]: 1,
                "cost": hostApi.runtime.number.random(hostApi.runtime.number.of(5), hostApi.runtime.number.of(15)),
            },
        }
    ]);
});
